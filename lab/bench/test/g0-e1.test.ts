function metadata(f: ReturnType<typeof fixture>, tag: string) {
  for (let i = 0; i < 2; i++) {
    const business = f.tables.tx_assertions![i]!,
      clock = business.recorded_at;
    const body = {
      op: "assert",
      tripleId: business.id,
      entityId: business.entity_id,
      attribute: "name",
      value: { type: "string", value: "fixed" + (i + 1) },
      validFrom: 10,
      recordedAt: clock,
      assertionTxId: business.tx_id,
    };
    for (const [kind, value] of [
      ["instant", clock],
      ["change", body],
    ] as const) {
      const row = {
        ...business,
        _id: JSON.stringify(["e1", tag + "meta" + kind + i]),
        id: tag + "meta" + kind + i,
        entity_id: business.tx_id,
        entity_type: "_Transaction",
        attribute: ":_tx/" + kind,
        valid_from: clock,
        value_type: kind === "instant" ? "datetime" : "json",
        value_string: null,
        value_datetime: kind === "instant" ? clock : null,
        value_json: kind === "change" ? JSON.stringify(value) : null,
        value_identity: JSON.stringify({ type: kind === "instant" ? "datetime" : "json", value }),
      };
      f.tables.tx_assertions!.push(row);
    }
  }
}
test("generated transaction metadata and its identity normalize but business JSON text does not", async () => {
  const a = fixture("a"),
    b = fixture("b");
  metadata(a, "a");
  metadata(b, "b");
  const want = { ...expected, counts: { ...expected.counts, tx_assertions: 6 } };
  const pa = await readE1G0(a.reader, want),
    pb = await readE1G0(b.reader, want);
  assert.notEqual(pa.D, pb.D);
  assert.equal(pa.Dprime, pb.Dprime);
  const row = b.tables.tx_assertions!.find((r) => r.attribute === ":_tx/change")!;
  row.value_json = String(row.value_json).replace('"validFrom":10', '"validFrom":10.0');
  assert.notEqual((await readE1G0(b.reader, want)).Dprime, pa.Dprime);
});
