const expected: Expected = {
  scope: "e1",
  position: 2,
  world: "N01",
  counts: { tx_assertions: 2, tx_claims: 2, tx_attempts: 2, tx_meta: 1 },
};
function fixture(tag: string) {
  const tables: Record<string, Record<string, unknown>[]> = Object.fromEntries(
    Object.keys(fields).map((t) => [t, []]),
  );
  for (let i = 1; i <= 2; i++) {
    const row = Object.fromEntries(fields.tx_assertions.map((c) => [c, null]));
    Object.assign(row, {
      _id: JSON.stringify(["e1", tag + "id" + i]),
      scope_key: "e1",
      id: tag + "id" + i,
      entity_id: "business" + i,
      attribute: "name",
      value_type: "string",
      value_string: "fixed" + i,
      value_identity: "fixed-identity" + i,
      recorded_position: i,
      recorded_at: 1000 * i + (tag === "a" ? 0 : 100),
      valid_from: 10,
      entity_type: "member",
      tx_id: tag + "tx" + i,
    });
    tables.tx_assertions!.push(row);
    tables.tx_claims!.push({
      _id: JSON.stringify(["e1", "command" + i]),
      scope_key: "e1",
      command_id: "command" + i,
      tx_id: tag + "tx" + i,
      recorded_at: row.recorded_at,
      position: i,
    });
    tables.tx_attempts!.push({
      _id: JSON.stringify(["e1", tag + "op" + i]),
      scope_key: "e1",
      operation_id: tag + "op" + i,
      attempt_id: tag + "attempt" + i,
      position: i,
    });
  }
  tables.tx_meta!.push({ _id: "e1", scope_key: "e1", position: 2 });
  const reader: Reader = {
    endpoint: tag,
    async count(t) {
      return tables[t]!.length;
    },
    async *scan(t) {
      yield* tables[t]!;
    },
    async scopes() {
      return [{ scope_key: "e1", position: 2 }];
    },
  };
  return { tables, reader };
}
test("independent seeds match Dprime but raw clone admission refuses changed generated bytes", async () => {
  const a = fixture("a"),
    b = fixture("b");
  const pa = await readE1G0(a.reader, expected),
    pb = await readE1G0(b.reader, expected);
  assert.notEqual(pa.D, pb.D);
  assert.equal(pa.Dprime, pb.Dprime);
  assert.ok(pa.Dprime);
  await assert.rejects(admitG0(b.reader, pa, expected));
  assert.equal((await admitG0(a.reader, pa, expected)).status, "PASS");
});
