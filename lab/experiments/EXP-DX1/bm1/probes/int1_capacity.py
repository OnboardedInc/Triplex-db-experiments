def command(*args, timeout=60, **kwargs):
    return subprocess.check_output(args, cwd=REPO, env=ENV, text=True, timeout=timeout, **kwargs).strip()


def call(*args, timeout=120, **kwargs):
    subprocess.run(args, cwd=REPO, env=ENV, check=True, timeout=timeout, **kwargs)


def status(state, following):
    now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    temporary = ROOT / f"status-{uuid.uuid4().hex}"
    temporary.write_text(f"item=int1-capacity state={state} since={now} next={following}\n")
    temporary.replace(ROOT.parent / "STATUS")


def cleanup():
    if not RUN.exists():
        return
    active = read(RUN)
    slot, mode = active["slot"], active["mode"]
    assert mode in ("small", "hot", "full")
    assert re.fullmatch(r"tx2-dx-bm1-cap-[0-9a-f]{12}-(small|hot|full)", slot)
    directory = ROOT / mode
    assert active == read(directory / "request.json") and active["source"] == seed.SOURCE
    logs = directory / "stopped-logs"
    logs.mkdir(exist_ok=True)
    for role in ("pg", *ROLES):
        with (logs / (role + ".txt")).open("ab") as stream:
            try:
                subprocess.run(["docker", "logs", "--timestamps", slot + "-" + role],
                               cwd=REPO, env=ENV, stdout=stream, stderr=subprocess.STDOUT, timeout=20)
            except subprocess.TimeoutExpired:
                stream.write(b"Log collection exceeded 20 seconds\n")
    call("bash", EXP / "stack/down.sh", slot, "--volumes")
    for args in (("ps", "-a"), ("volume", "ls"), ("network", "ls")):
        assert not any(name.startswith(slot + "-") for name in command("docker", *args, "--format", "{{.Names}}" if args[0] == "ps" else "{{.Name}}").splitlines())
    write(directory / "cleanup.json", dict(slot=slot, nonce=active["nonce"], remaining=[],
                                           requestSha256=sha(directory / "request.json")))
    RUN.unlink()


def cohort_for(people):
    return [i * 50 + ((31 * i + 17 * (i // 40) + 29) % 50 if i else 0)
            for i in range(people // 50)]


def expected_digest(oracle, subject, position):
    # [DX-BM1] Why: compute the typed world hash from the saved oracle row inputs independently.
    # Rejected: certifying two equal digest strings generated by the same faulty observer.
    def typed(value):
        if isinstance(value, str):
            return ["string", value]
        if isinstance(value, bool):
            return ["boolean", value]
        if isinstance(value, (int, float)):
            return ["number", str(int(value)) if value == int(value) else str(value)]
        if isinstance(value, dict):
            return ["object", [[key, typed(value[key])] for key in sorted(value)]]
        assert value is None
        return ["null"]

    valid = 1793793600000
    parts = []
    for (batch,) in oracle.execute("SELECT body FROM wanted WHERE i=? AND p<=? ORDER BY p", (subject, position)):
        for row in json.loads(batch):
            op = row["op"]
            if op["validFrom"] > valid:
                continue
            concrete = {"id": row["id"], "entityId": op["entityId"], "attribute": op["attribute"],
                "value": op["value"], "recordedAt": row["instant"], "validFrom": op["validFrom"]}
            keys = {key: typed(value) for key, value in concrete.items()}
            for key in ("validTo", "retractedAt", "entityType", "retractTxId"):
                keys[key] = ["option", "None", []]
            for key, value in (("createdBy", "import"), ("schemaVersion", 1), ("txId", row["txId"])):
                keys[key] = ["option", "Some", typed(value), []]
            parts.append(seed.line(["row", [[key, keys[key]] for key in sorted(keys)]]))
    return len(parts), hashlib.sha256(("[" + ",".join(sorted(parts)) + "]").encode()).hexdigest()


def collect_mode(directory):
    # [DX-BM1] Why: cross-check the actual offered roots, basis and native ACK order independently of the producer.
    # Rejected: trusting an aggregate count after transport or native-verification failures.
    request, reading = read(directory / "request.json"), read(directory / "reading.json")
    assert reading["requestSha256"] == sha(directory / "request.json")
    assert read(directory / "cleanup.json") == dict(slot=request["slot"], nonce=request["nonce"],
        remaining=[], requestSha256=reading["requestSha256"])
    assert all(reading[k] == request[k] for k in ("source", "mode", "slot", "people"))
    assert (directory / "observations.jsonl").stat().st_mtime >= request["start"]
    assert (directory / "reading.json").stat().st_mtime >= (directory / "observations.jsonl").stat().st_mtime
    people = reading["people"]
    n = 20 if people == 1000 else 1000
    cohort = cohort_for(people)
    chosen = cohort[::len(cohort) // n]
    cut = reading["seedCut"]
    if reading["mode"] != "hot":
        assert cut == request["seed"]["cut"] and reading["scope"] == request["seed"]["scope"]
    else:
        assert cut == math.ceil(len(cohort) / 48) and reading["scope"] == request["slot"] + "-hot"
    assert reading["cohortSha256"] == hashlib.sha256(seed.line(cohort).encode()).hexdigest()
    identity = [request["source"], request["slot"], reading["scope"], reading["mode"], people,
                request["nonce"], request["snapshotSha256"]]
    assert reading["binding"] == hashlib.sha256(seed.line(identity).encode()).hexdigest()
    assert reading["reads"] == len(cohort) + 3*n and reading["firstReads"] == len(cohort)
    assert reading["saves"] == n and reading["finalCut"] == cut + n
    measures, stages, roles = [], {}, {}
    receipts = set()
    timing = {phase: [] for phase in ("first", "save", "own", "resident", "past")}
    access = read(directory / "access.json")
    assert read(directory/"runtime-flags.json")["slot"] == request["slot"]
    runtime = read(directory/"runtime-flags.json")["roles"]

    def resource(row, label, position):
        assert row["kind"] == "resources" and row["label"] == label and row["cut"] == position
        assert row["at"] / 1000 >= request["start"] and row["binding"] == reading["binding"]
        assert row["native"]["disk"]["fsync"] == row["native"]["disk"]["synchronousCommit"] == row["native"]["disk"]["fullPageWrites"] == "on"
        participants = row["native"]["roles"]
        assert set(participants) == {"pg", *ROLES}
        for name, values in participants.items():
            actual, = [p for p in access["containers"] if p["name"] == request["slot"]+"-"+name]
            assert actual["id"] == values["container"] and values["rssBytes"] > 0
        cache = row["reader"]["scopes"][reading["scope"]]
        measures.append(dict(label=label, cut=position, cache=cache, reader=row["reader"]["rssBytes"],
            roles={name: info["rssBytes"] for name, info in participants.items()},
            databaseBytes=row["native"]["disk"]["database"]))

    def answer(oracle, row, kind, subject, position):
        assert [row[k] for k in ("kind", "subject", "position")] == [kind, subject, position]
        assert request["start"] <= row["start"] / 1000 <= row["finish"] / 1000
        count, expected = expected_digest(oracle, subject, position)
        assert row["observed"] == row["expected"] == expected and count == row["facts"] > 0
        timing[kind].append(row["finish"] - row["start"])

    raw = directory / "observations.jsonl"
    with raw.open() as stream, sqlite3.connect((directory/"measurement.sqlite").as_uri()+"?mode=ro", uri=True) as oracle:
        rows = map(json.loads, stream)
        resource(next(rows), "before-activity", cut)
        for subject in cohort:
            answer(oracle, next(rows), "first", subject, cut)
        for index in range(3):
            resource(next(rows), "fixed-" + str(index), cut)
        for index, subject in enumerate(chosen, 1):
            row = next(rows)
            position = cut + index
            assert [row[k] for k in ("kind", "subject", "position")] == ["save", subject, position]
            binding = reading["binding"] if reading["mode"] == "hot" else request["seed"]["binding"]
            assert row["command"] == f"{binding[:18]}-{position}"
            assert row["receipt"] and row["receipt"] not in receipts
            wanted, = oracle.execute("SELECT body FROM wanted WHERE i=? AND p=?", (subject, position)).fetchone()
            matching, = json.loads(wanted)
            assert matching["txId"] == row["receipt"] and matching["instant"] == row["clock"]
            assert matching["op"]["attribute"] == "bgcStatus"
            assert matching["op"]["value"] == {"type": "string", "value": "consider"}
            receipts.add(row["receipt"])
            assert request["start"] <= row["start"]/1000 <= row["verified"]/1000
            assert math.isfinite(row["clock"])
            assert 0 < row["nativeAckMs"] <= row["verified"] - row["start"] + 0.001
            timing["save"].append(row["nativeAckMs"])
            answer(oracle, next(rows), "own", subject, position)
            answer(oracle, next(rows), "resident", subject, position)
            answer(oracle, next(rows), "past", subject, position - 1)
        resource(next(rows), "after-activity", cut+n)
        assert next(rows, None) is None
    for name, cpus in ROLES.items():
        logs = sorted((directory/"engines"/request["slot"]/"trace/raw").glob(name+".gc.log*"))
        assert logs and runtime[name]["cpus"] == cpus and runtime[name]["collector"] == "G1"
        for file in logs:
            assert file.stat().st_mtime >= request["start"]
            assert re.search(rb"(?m)^\[\d{4}-\d\d-\d\dT", file.read_bytes())
            stages[name] = {**stages.get(name, {}), file.name: sha(file)}
        roles[name] = {**runtime[name], "cores": len(cpus.split(",")), "gcLogs": stages[name]}

    def percentile(values, confidence):
        return sorted(values)[math.ceil(confidence*len(values))-1]

    result = {**reading, "observationsSha256": sha(raw), "resources": measures, "roles": roles,
              "timingMs": {phase: dict(n=len(values), p50=percentile(values, .5), p99=percentile(values, .99))
                           for phase, values in timing.items()}}
    write(directory / "collector.json", result)
    return result


def collect_profiles(results):
    hot, full = results
    assert hot["mode"] == "hot" and full["mode"] == "full"
    assert hot["cohortSha256"] == full["cohortSha256"] and hot["firstReads"] == full["firstReads"] == 20000

    def point(reading, role):
        fixed = reading["resources"][1:4]
        samples = [row["reader"] if role == "reader" else row["roles"][role] for row in fixed]
        return sorted(samples)[1]

    roles = ("reader", "pg", *ROLES)
    rss = {role: {"onlyActive": point(hot, role), "full": point(full, role),
                  "differencePerUntouchedPerson": (point(full, role) - point(hot, role))/980000}
           for role in roles}
    write(ROOT/"comparison.json", {"source": seed.SOURCE, "readerCohort": 20000, "coldPopulation": 980000,
        "rssBytes": rss, "controls": {r["mode"]: sha(ROOT/r["mode"]/"collector.json") for r in results}})


def boot(mode, sealed):
    directory = ROOT/mode
    directory.mkdir()
    nonce = uuid.uuid4().hex[:12]
    slot = f"tx2-dx-bm1-cap-{nonce}-{mode}"
    people = 1000 if mode == "small" else 1_000_000
    retained = None
    if mode != "hot":
        name = "small" if mode == "small" else "full"
        retained = read(seed.ROOT/name/"verified.json")
        assert retained["source"] == seed.SOURCE and retained["people"] == people
        assert retained["ledgerSha256"] == sha(seed.ROOT/name/"population.sqlite")
        assert sealed[name + "Sha256"] == sha(seed.ROOT/name/"verified.json")
        copy = directory / "oracle.sqlite"
        shutil.copyfile(seed.ROOT/name/"population.sqlite", copy)
        retained = {**retained, "ledger": str(copy)}
    request = dict(slot=slot, nonce=nonce, source=seed.SOURCE, mode=mode, people=people, seed=retained,
                   start=time.time(), snapshotSha256=sealed["snapshot"]["sha256"])
    write(directory / "request.json", request)
    write(RUN, request)
    ENV.update(DX_BARE_METAL_ROOT=str(directory), DX_STACK_EVIDENCE=str(directory/"engines"),
               TRIPLEX_TRACE_SOURCE=seed.SOURCE, TRIPLEX_TRACE_RUN=slot, TRIPLEX_TRACE_SLOT=slot)
    try:
        def gc(role):
            return f"-XX:+UseG1GC -Xlog:gc*=info:file=/trace/{role}.gc.log:time,uptimemillis,level,tags:filecount=4,filesize=8m"

        for role, key in (("gw-w", "DX_GW_WRITE_JAVA_OPTS"), ("gw-r", "DX_GW_READ_JAVA_OPTS")):
            ENV[key] = "-Xms64m -Xmx384m -Ddatomic.objectCacheMax=32m -XX:MinHeapFreeRatio=15 -XX:MaxHeapFreeRatio=30 -XX:-ShrinkHeapInSteps " + gc(role)
        call("bash", EXP/"stack/up.sh", slot, "--no-publish", "--cpus-tx", "0", "--cpus-pg", "1",
             "--cpus-gw-write", "2", "--cpus-gw-read", "4,8", "--tx-memory", "5g", "--pg-memory", "4g",
             "--tx-java-opts", "-Xms256m -Xmx3g " + gc("tx"), "--object-cache-max", "1280m", timeout=240)
        state = directory/"engines"/slot
        stack = read(state/"stack.json")
        assert stack["prefix"] == slot and len(stack["containers"]) == 4
        if retained:
            status("restoring-" + mode, "offer")
            dump = seed.ROOT/"seed.pgdump"
            assert dump.stat().st_size == sealed["snapshot"]["bytes"] and sha(dump) == sealed["snapshot"]["sha256"]
            names = [slot + "-" + role for role in ("gw-r", "gw-w", "tx")]
            call("docker", "stop", "--time", "15", *names, timeout=70)
            pg = slot + "-pg"
            call("docker", "update", "--cpuset-cpus", "1,9,10,11", pg)
            target = "/tmp/bm1-capacity.pgdump"
            call("docker", "cp", dump, pg+":"+target, timeout=180)
            assert command("docker", "exec", pg, "sha256sum", target, timeout=90).split()[0] == sealed["snapshot"]["sha256"]
            with (directory/"pg-restore.log").open("xb") as log:
                call("docker", "exec", pg, "pg_restore", "--jobs=4", "-U", "postgres", "--exit-on-error",
                     "--clean", "--if-exists", "-d", "datomic", target, timeout=720, stdout=log, stderr=subprocess.STDOUT)
            call("docker", "exec", pg, "rm", target)
            call("docker", "update", "--cpuset-cpus", "1", pg)
            restart = datetime.now(timezone.utc).isoformat()
            call("docker", "start", slot+"-tx", timeout=60)
            until = time.monotonic() + 90
            while "System started" not in command("docker", "logs", "--since", restart, slot+"-tx",
                                                   stderr=subprocess.STDOUT).splitlines()[-80:]:
                if time.monotonic() >= until:
                    raise TimeoutError("Restored transactor startup")
                time.sleep(1)
            call("docker", "start", *names[:2])

        profiles = {}
        for role, cpus in ROLES.items():
            item, = [c for c in stack["containers"] if c["name"] == slot+"-"+role]
            info, = json.loads(command("docker", "inspect", item["id"]))
            assert info["State"]["Running"] and item["cpuset"] == info["HostConfig"]["CpusetCpus"] == cpus
            log = (state/"trace/raw"/(role+".gc.log"))
            until = time.monotonic() + 60
            while not log.is_file() or "Using G1" not in log.read_text():
                if time.monotonic() >= until:
                    raise TimeoutError("No fresh G1 flag for " + role)
                time.sleep(1)
            profiles[role] = dict(container=item["id"], cpus=cpus, collector="G1",
                                  startedAt=info["State"]["StartedAt"])
        write(directory / "runtime-flags.json", {"slot": slot, "roles": profiles})
        for role, field in (("w","writeUrl"), ("r","readUrl")):
            ip = command("docker", "inspect", "--format", "{{range .NetworkSettings.Networks}}{{.IPAddress}}{{end}}", slot+"-gw-"+role)
            assert re.fullmatch(r"(?:[0-9]{1,3}\.){3}[0-9]{1,3}", ip)
            stack[field] = f"http://{ip}:8080"
            call("curl", "-fsS", "--retry", "30", "--retry-all-errors", "--retry-delay", "1", "--max-time", "5",
                 stack[field]+"/health", timeout=65, stdout=subprocess.DEVNULL)
        access = directory/"access.json"
        write(access, stack)
        commands = directory/"commands"
        commands.mkdir()
        shutil.copy(HERE/"int1-docker-top.sh", commands/"docker")
        (commands/"docker").chmod(0o755)
        local_env = dict(ENV, PATH=str(commands)+":"+ENV["PATH"], DATOMIC_URL=stack["writeUrl"],
            DATOMIC_READ_URLS=stack["readUrl"], DX_BM1_DOCKER_NATIVE=shutil.which("docker"),
            DX_BM1_INT1_CONTAINER_IDS=" ".join(c["id"] for c in stack["containers"]))
        status("measuring-"+mode, "collector")
        subprocess.run([NODE, "lab/bin/heavy.mjs", "--label", "DX-BM1-int1-"+mode, "--", "taskset", "-c", "3",
            NODE, "--import", "tsx", "--expose-gc", HERE/"int1-capacity.mjs", directory/"request.json"],
            cwd=REPO, env=local_env, check=True, timeout=2200)
    finally:
        cleanup()
    return collect_mode(directory)


