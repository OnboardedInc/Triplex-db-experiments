// [EXP-X02-R4] Why: derive token boundaries from the pinned ANTLR lexer, including
// longest-match identifiers and string escapes. Rejected: adding spelling exceptions per review.
import fs from "node:fs";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
const input = new URL("../packages/xtdb/test/fixtures/SqlLexer-v2.2.0.g4", import.meta.url);
const output = new URL("../packages/xtdb/src/native/SqlLexerPatterns.ts", import.meta.url);
const source = fs.readFileSync(input, "utf8");
const rules = new Map(
  [...source.matchAll(/^(?:fragment )?([A-Z_]+)\s*:\s*([\s\S]*?);[ \t]*$/gm)].map((m) => [
    m[1],
    m[2]
      .replace(/\s+->.*$/s, "")
      .replace(/\s+\{.*$/s, "")
      .trim(),
  ]),
);
const escape = (s) => s.replace(/[.*+?^\x24{}()|[\]\\]/g, "\\$&");
const cache = new Map();
const compile = (name) => {
  if (cache.has(name)) return cache.get(name);
  if (!rules.has(name)) throw Error("Unknown lexer fragment " + name);
  const text = rules.get(name);
  let i = 0;
  const atom = () => {
    while (/\s/.test(text[i] ?? "") && i < text.length) i++;
    const c = text[i++];
    if (c === "'") {
      let value = "",
        closed = false;
      while (i < text.length) {
        const a = text[i++];
        if (a === "'") {
          closed = true;
          break;
        }
        if (a === "\\") {
          const b = text[i++];
          value += { n: "\n", r: "\r", t: "\t" }[b] ?? b;
        } else value += a;
      }
      if (!closed) throw Error("Unclosed literal");
      return escape(value);
    }
    if (c === "[") {
      const begin = i - 1;
      while (i < text.length) {
        if (text[i++] === "]") return text.slice(begin, i);
      }
      throw Error("Unclosed class");
    }
    if (c === "(") {
      const value = expression(")");
      if (text[i++] !== ")") throw Error("Unclosed group");
      return "(?:" + value + ")";
    }
    if (c === "~") return "(?!(?:" + atom() + "))[\\s\\S]";
    if (/[A-Z_]/.test(c ?? "")) {
      let name = c;
      while (/[A-Z_0-9]/.test(text[i] ?? "") && i < text.length) name += text[i++];
      return "(?:" + compile(name) + ")";
    }
    throw Error("Unsupported lexer syntax " + name + " at " + (i - 1) + ": " + c);
  };
  const expression = (stop) => {
    let value = "";
    while (i < text.length) {
      while (/\s/.test(text[i] ?? "") && i < text.length) i++;
      if (i === text.length || text[i] === stop) break;
      if (text[i] === "|") {
        value += "|";
        i++;
        continue;
      }
      let a = atom();
      while (/\s/.test(text[i] ?? "") && i < text.length) i++;
      if (["*", "+", "?"].includes(text[i])) a = "(?:" + a + ")" + text[i++];
      value += a;
    }
    return value;
  };
  const result = expression(undefined);
  if (i !== text.length) throw Error("Unconsumed lexer rule " + name);
  cache.set(name, result);
  return result;
};
const names = [...rules.keys()].filter(
  (n) =>
    !source.includes("fragment " + n + " ") &&
    !["BLOCK_COMMENT", "LINE_COMMENT", "DM_END_TAG", "DM_TEXT"].includes(n),
);
// [EXP-X02-R4] Why: keyword rules and REGULAR_IDENTIFIER have identical word
// boundaries; retain the complete lexeme and classify its ASCII spelling later.
// Rejected: hundreds of redundant regex matches per token.
const boundaryNames = names.filter(
  (name) =>
    !/^'[A-Za-z_][A-Za-z0-9_]*'(?:\s*\|\s*'[A-Za-z_][A-Za-z0-9_]*')*$/.test(rules.get(name)),
);
const patterns = boundaryNames.map((name) => ({ name, source: "^(?:" + compile(name) + ")" }));
let generated =
  "// [EXP-X02-R4] Why: generated by scripts/generate-xtdb-lexer.mjs from XTDB v2.2.0 SqlLexer.g4.\n// Rejected: independent handwritten identifier, whitespace or string rules. Do not edit by hand.\n";
generated +=
  "export const pinnedLexerSha256 = " +
  JSON.stringify(createHash("sha256").update(source).digest("hex")) +
  ";\n";
generated +=
  "export const sqlLexerPatterns: readonly { readonly name: string; readonly source: string }[] = " +
  JSON.stringify(patterns, null, 2) +
  ";\n";
const formatted = spawnSync(
  new URL("../node_modules/.bin/oxfmt", import.meta.url).pathname,
  ["--stdin-filepath", output.pathname],
  { input: generated, encoding: "utf8" },
);
if (formatted.status !== 0) throw Error(formatted.stderr || "Lexer formatting failed");
generated = formatted.stdout;
if (process.argv.includes("--check")) {
  if (fs.readFileSync(output, "utf8") !== generated)
    throw Error("Generated XTDB lexer patterns are stale");
} else fs.writeFileSync(output, generated);
console.log("Derived", patterns.length, "token rules");
